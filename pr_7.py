# ============================================================
# 변수(variable) = 값이 들어 있는 "상자"가 아니라 "이름표"
# - a = 1  → 이름 a가 객체 1을 가리킴
# - a = "1" → 이름 a가 새 객체 "1"을 가리킴 (기존 1 자리를 덮어쓰는 게 아님)
# - 재할당(이름 옮기기) vs 수정(같은 객체 안을 바꾸기)을 구분할 것
# ============================================================

# --- 1) 재할당: 같은 이름, 다른 객체 --------------------------------
a = 1
print(f"처음 a = {a!r}, type = {type(a)}, id = {id(a)}")

a = "1"  # 새 문자열 객체를 만들고, 이름 a만 그쪽으로 이동
print(f"재할당 후 a = {a!r}, type = {type(a)}, id = {id(a)}")
# → 타입이 int → str 로 바뀐 것처럼 보여도,
#   실제로는 "같은 공간에 덮어쓴 것"이 아니라 "가리키는 대상이 바뀐 것"
#   (!r 은 문자열이면 '1'처럼 따옴표 포함해 보여 줌)

# --- 2) 이름 공유 후 한쪽만 재할당 ----------------------------------
# 튜플 때와 같은 논리
a = (1, 2, 3)
b = a  # b는 a의 값을 복사한 게 아니라, 같은 객체를 같이 가리킴
print(f"공유 직후 a = {a}, b = {b}")
print(f"같은 객체? id(a) == id(b) → {id(a) == id(b)}")

a = (10, 2, 3)  # a만 새 튜플을 가리킴. (1,2,3)은 수정되지 않음
print(f"a만 재할당 후 a = {a}")
print(f"b는 그대로     b = {b}")  # b는 여전히 (1, 2, 3)

# --- 3) b도 a를 다시 가리키면, 예전 객체는 참조 0개 ------------------
# (1, 2, 3)을 보던 이름이 없어지면 → GC 대상 (곧바로가 아니라 "회수 가능")
b = a
print(f"b = a 다시 수행 후 a = {a}, b = {b}")
print(f"다시 같은 객체? id(a) == id(b) → {id(a) == id(b)}")
# 이제 (1, 2, 3)을 가리키는 변수가 없으면, 그 메모리는 나중에 정리될 수 있음

# --- 4) 숫자/문자열도 동일 ------------------------------------------
x = 1
y = x
x = "1"  # x만 새 객체로 이동
print(f"숫자→문자열 재할당: x = {x!r}, y = {y!r}")  # y는 여전히 1

# --- 5) 리스트는 "재할당"과 "수정"이 다름 (중요) --------------------
# 재할당: 이름이 다른 객체를 가리킴
# 수정  : 같은 리스트 객체 안의 내용을 바꿈 → 같이 보던 이름 모두 영향

list_a = [1, 2, 3]
list_b = list_a  # 같은 리스트를 공유
print(f"공유 직후 list_a = {list_a}, list_b = {list_b}")

list_a[0] = 100  # 재할당이 아니라 "수정" (같은 객체 안을 변경)
print(f"list_a[0]=100 후 list_a = {list_a}")
print(f"list_b도 같이 변함 list_b = {list_b}")  # 같은 객체를 보므로 100

list_a = [9, 9, 9]  # 이번엔 재할당: list_a만 새 리스트를 가리킴
print(f"list_a 재할당 후 list_a = {list_a}")
print(f"list_b는 예전 리스트  list_b = {list_b}")  # [100, 2, 3]

# --- 6) id로 객체 구분해 보기 ----------------------------------------
p = 1
q = 1
print(f"p = 1, q = 1 / id(p) = {id(p)}, id(q) = {id(q)}")
# 작은 정수는 같은 객체를 재사용할 수 있음 (인터너). "값이 같다"와 "항상 새 공간"은 별개.
# 핵심은 여전히: 변수는 상자 공간이 아니라 객체를 가리키는 이름표.

# --- 7) 정리 ---------------------------------------------------------
# 변수 a = 이름표 (고정 메모리 칸이 아님)
# a = 1  다음 a = "1" → 새 객체를 가리키도록 이름만 옮김
# b = a  후 a만 재할당 → b는 예전 객체를 유지
# b = a  를 다시 하면 예전 객체는 참조가 없으면 GC 대상
# 리스트[0] = ... 는 재할당이 아니라 같은 객체 수정 → 공유 이름 모두 영향

